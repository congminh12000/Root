import { expect, test } from '@playwright/test'

test('context button cancels locally, sends on keyboard activation, and blocks mandatory decisions', async ({ page }) => {
  await page.goto('/ui-kit.html')
  const demo = page.locator('[data-context-demo]')
  const mode = demo.getByLabel('Ngữ cảnh nút chính')
  const main = demo.locator('.context-action')
  await expect(main).toHaveText('Sang Evening ▷')
  await mode.selectOption('cancel')
  await expect(main).toHaveText('Huỷ')
  await main.click()
  await expect(demo.locator('[data-sent]')).toHaveText('Đã gửi: 0')
  await expect(main).toHaveText('Sang Evening ▷')
  await main.focus()
  await page.keyboard.press('Enter')
  await expect(demo.locator('[data-sent]')).toHaveText('Đã gửi: 1')
  await mode.selectOption('continue')
  await expect(main).toHaveText('Tiếp tục ▷')
  await mode.selectOption('march')
  await expect(main).toHaveText('Dừng March ▷')
  await mode.selectOption('blocked')
  await expect(main).toBeDisabled()
  await expect(demo.locator('[data-sent]')).toHaveText('Đã gửi: 1')
})
for (const [width, height] of [[1440, 900], [1280, 800], [1180, 820], [820, 1180]] as const) {
  test(`context action fits and is a large touch target at ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.goto('/ui-kit.html')
    const demo = page.locator('[data-context-demo]')
    await demo.scrollIntoViewIfNeeded()
    const button = demo.locator('.context-action')
    const bounds = await button.boundingBox()
    expect(bounds!.height).toBeGreaterThanOrEqual(48)
    expect(bounds!.width).toBeGreaterThanOrEqual(120)
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    await demo.screenshot({ path: `test-results/rd-m07-${width}.png` })
  })
}
